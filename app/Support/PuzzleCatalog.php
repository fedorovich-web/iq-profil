    public static function find(string $kind): ?array
    {
        foreach (self::definitions() as $definition) {
            if ($definition[0] === $kind) {
                return $definition;
            }
        }

        return null;
    }

    public static function categoryFor(string $kind): string
    {
        foreach (self::definitions() as $index => $definition) {
            if ($definition[0] === $kind) {
                return [
                    'Базовые закономерности',
                    'Комбинации фигур',
                    'Повороты и симметрия',
                    'Работа с несколькими правилами',
                    'Составные задачи',
                ][intdiv($index, 5)];
            }
        }

        return [
            'dots' => 'Количество элементов',
            'polygon' => 'Геометрические фигуры',
            'rotation' => 'Повороты и направления',
            'stripes' => 'Линии и последовательности',
            'position' => 'Расположение в сетке',
        ][$kind] ?? 'Графические задания';
    }
